import fs from 'node:fs';
import assert from 'node:assert/strict';
import {execFileSync} from 'node:child_process';
const read=p=>fs.readFileSync(p,'utf8').replaceAll('\r\n','\n');
const page=read('apps/operations/reports.php'), profile=read('apps/operations/kpi-employee.php');
const css=read('assets/css/performance-dashboard.css'), js=read('assets/js/reports-business-health.js');
assert.match(profile,/\$canReview \? 'reports.php' : '\.\.\/\.\.\/index.php'/);
assert.ok(page.indexOf("'assets/css/performance-dashboard.css'")<page.indexOf("include BASE_PATH . '/shared/header.php'"));
assert.doesNotMatch(page,/<link rel="stylesheet"/,'no delayed report stylesheet');
assert.ok(page.indexOf('id="kpi-business-timeline"')<page.indexOf('<section data-kpi-section-content>'),'filters precede results');
assert.match(page,/Team Comparison/);assert.match(page,/← Employee Dashboard/);
for(const id of ['reporting-controls','employee-schedules','working-calendar','tracking-history'])assert.ok(page.includes(`id="${id}"`));
assert.match(css,/Jost/);assert.match(css,/#366b96/);assert.match(css,/#59694a/);assert.match(css,/prefers-reduced-motion/);
assert.doesNotMatch(css,/Figtree|#721b1a|#f07420|#ab3619/i);
assert.match(js,/version !== requestVersion/);assert.match(js,/AbortController/);assert.match(js,/Operational score · not an employee score/);
const base=execFileSync('git',['show','0d4e0c10:apps/operations/reports.php'],{encoding:'utf8'}).replaceAll('\r\n','\n');
const handlers=s=>s.slice(s.indexOf('$ready ='),s.indexOf("include BASE_PATH . '/shared/header.php'"));
assert.equal(handlers(page),handlers(base),'settings values, validation, writes and permissions unchanged');
const beforeHooks=[...base.matchAll(/data-(?:kpi|activity|performance)-[a-z-]+/g)].map(m=>m[0]);
for(const hook of new Set(beforeHooks))assert.ok(page.includes(hook),`preserve ${hook}`);
console.log('PASS: dashboard navigation, early theme, filter order, shared styling, request guards, settings and all report hooks');
