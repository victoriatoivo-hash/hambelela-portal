import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
const read = (path) => readFileSync(new URL(`../${path}`, import.meta.url), 'utf8');
const viewBar = read('assets/js/portal-view-bar.js');
const viewCss = read('assets/css/portal-view-bar.css');
const courier = read('apps/operations/courier.php');
const bookkeeping = read('apps/operations/bookkeeping.php');
const errors = read('apps/operations/errors.php');
assert.match(viewBar, /\.courier-wrap \.filter-strip/, 'Courier filter must use the shared view bar');
assert.match(viewBar, /source\.querySelector\('\.work-filter-actions/, 'Packing actions must be moved from their real action host');
assert.match(viewBar, /insertBefore\(action, overflow\)/, 'Page actions must appear before More, directly after Group');
assert.match(viewBar, /source\.querySelector\('form'\) \|\| source/, 'Client-side filters must initialise without a form');
assert.match(viewCss, /portal-view-bar__popover \.portal-view-bar-source\{display:block!important/, 'Moved filter surfaces must be visible');
assert.match(courier, /data-courier-tools-open data-view-bar-action/, 'Courier tools must move into the shared bar');
assert.match(bookkeeping, /id="bkDrawerBtn" data-view-bar-action/, 'Cash tools must move into the shared bar');
assert.match(viewCss, /\.bk-drawer\{z-index:60000!important\}/, 'Cash drawer must cover header status controls');
assert.match(errors, /name="search"/, 'Error Log must expose search');
assert.match(errors, /el\.error_title LIKE \? OR el\.description LIKE \?/, 'Error Log search must filter its dataset');
assert.match(viewCss, /\.workspace\.module\.digital-task-page.*width:100%!important/s, 'Task Management must fill the workspace');
console.log('cross-page toolbar and panel layering contract passed');
