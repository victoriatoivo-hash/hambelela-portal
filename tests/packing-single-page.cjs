const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const root = path.join(__dirname, '..');
const source = fs.readFileSync(path.join(root, 'assets/js/packing-list.js'), 'utf8');
const tasks = Array.from({length: 620}, (_, id) => ({id, date_loaded: id < 510 ? '2026-09-15' : '2026-01-12'}));
tasks.push({id: 621, date_loaded: '2025-09-15'});
const state = {search: '', date: '2026-09'};
const context = vm.createContext({tasks, state, labelText: () => '', statuses: [], priorities: []});
vm.runInContext(source.slice(source.indexOf('  function visibleTasks()'), source.indexOf('  function groupKey(')), context);
assert.equal(context.visibleTasks().length, 510);
state.date = '2026';
assert.equal(context.visibleTasks().length, 620);
state.date = '';
assert.equal(context.visibleTasks().length, 621);
assert(source.includes('const pageRows = visible;'));
assert(!source.includes('const pageRows = visible.slice'));
assert(source.includes('date: currentMonth'));
assert(!fs.readFileSync(path.join(root, 'apps/operations/packing-list-data.php'), 'utf8').includes('LIMIT 500'));
assert(fs.readFileSync(path.join(root, 'apps/operations/consignments.php'), 'utf8').includes('Packing month or year'));
console.log('PASS: month/year filtering keeps all 510/620 rows; no pagination or 500-row truncation.');
