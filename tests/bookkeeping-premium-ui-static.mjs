import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const read=p=>readFileSync(new URL('../'+p,import.meta.url),'utf8');
const page=read('apps/operations/bookkeeping.php');
const css=read('assets/css/bookkeeping-essentials.css');
const js=read('assets/js/bookkeeping-essentials.js');
const toolbar=read('assets/js/portal-view-bar.js');
for(const partial of ['ess-sidebar.php','ess-topbar.php','ess-navigation.php']) assert.ok(page.includes(partial),partial);
assert.ok(css.includes('--book-600:#28639B'));
assert.ok(css.includes("font-family:'Jost',sans-serif!important"));
assert.ok(css.includes('prefers-reduced-motion:reduce'));
assert.ok(css.includes('grid-template-columns:1fr!important'));
assert.ok(js.includes("source.type='hidden'"),'Only one ledger search control');
assert.ok(js.includes('previousInert'),'Drawer restores prior inert state');
assert.ok(js.includes("e.key !== 'Tab'"),'Drawer traps keyboard focus');
assert.ok(page.includes('aria-modal="true"'));
assert.ok(toolbar.includes(":scope > .entry-row"),'Sorting excludes add-entry rows');
const filterBody=page.slice(page.indexOf('function applySidebarFilters()'),page.indexOf('function syncBookkeepingFilterOptions()'));
assert.ok(filterBody.includes('recalcStats();'),'Today cards stay scoped to today after filters');
assert.equal((page.match(/data-closing-balance>/g)||[]).length,1,'One current balance value');
assert.ok(page.includes('book-current-kpi'));
assert.ok(!page.includes('class="closing-card"'),'Bottom balance component removed');
assert.ok(!css.includes('.closing-card'),'Bottom balance styles removed');
assert.ok(!page.includes('type="color"'),'No native colour picker in Bookkeeping');
assert.ok(js.includes("['Bookkeeping blue','#28639B']"));
assert.ok(js.includes("document.body.append(menu)"),'Nested menus escape transformed popover ancestors');
assert.ok(js.includes("book-select-cancel"),'Custom inline selects can cancel without writes');
assert.ok(page.includes("portal-date-close"),'Custom inline date editing can cancel without writes');
assert.ok(read('assets/js/portal-date-picker.js').includes("classList.toggle('book-date-picker'"),'Date visual scope is explicit');
console.log('Bookkeeping premium UI contract checks passed.');
