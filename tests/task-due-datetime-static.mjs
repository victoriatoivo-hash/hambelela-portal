import fs from 'node:fs';
import assert from 'node:assert/strict';

const read = (path) => fs.readFileSync(new URL(`../${path}`, import.meta.url), 'utf8');
const tasks = read('apps/operations/checklists.php');
const picker = read('assets/js/portal-date-picker.js');
const portalCss = read('assets/css/portal.css');

const createForm = tasks.match(/<form class="task-create-form[\s\S]*?<\/form>/)?.[0] || '';
assert.match(createForm, /Due date and time/);
assert.match(createForm, /name="due_at"[^>]*data-task-due-value[^>]*required/);
assert.match(createForm, /data-enable-time="true"/);
assert.doesNotMatch(createForm, /data-task-due-date|data-task-due-time/);
assert.equal((createForm.match(/name="due_at"/g) || []).length, 1, 'New Task must submit exactly one due_at value');
assert.match(tasks, /function checklist_create_due_at\(array \$request\): string/);
assert.match(tasks, /function checklist_parse_windhoek_datetime\(string \$raw\)/);
assert.match(tasks, /'d\/m\/Y h:i A'/, 'the server keeps a strict legacy display-format fallback');
assert.match(tasks, /'code' => \$code, 'message' => \$message, 'field' => \$field/, 'date errors must be structured by field');
assert.match(tasks, /new DateTimeZone\('Africa\/Windhoek'\)/);
assert.match(tasks, /This time has already passed\. Select a future time\./);
assert.match(tasks, /\$deadline = \$taskMode === 'recurring' \? '' : checklist_create_due_at\(\$_POST\)/);
assert.match(tasks, /const validateDueAt = \(\) =>/);
assert.match(tasks, /second=match\[6\]===undefined\?0:Number\(match\[6\]\)/, 'optional seconds must default before numeric conversion');
assert.match(tasks, /const requestData=new FormData\(form\)/, 'the audited active form must provide the request payload');
assert.match(tasks, /if\(result\.field==='due_at'\)/, 'server due errors must attach to the active due field');
assert.match(tasks, /\.replace\(\/\^0\/, ''\)\.toUpperCase\(\)/, 'The contextual summary must use unpadded 12-hour AM/PM text');
assert.doesNotMatch(tasks, /Assign the task anyway\?/);
assert.match(picker, /data-time-hour/);
assert.match(picker, /data-time-minute/);
assert.match(picker, /data-time-meridiem/);
assert.match(picker, /data-portal-date-now/);
assert.match(picker, /data-portal-date-clear/);
assert.match(picker, /data-portal-date-cancel/);
assert.match(picker, /data-portal-date-apply/);
assert.match(picker, /function resolveSubmitTarget\(input\)/, 'date targets must be resolved by the active picker context');
assert.match(picker, /queryWithin\(wrapper, selector\) \|\| queryWithin\(form, selector\)/, 'date targets must prefer the active wrapper/form');
assert.match(picker, /matches\.length === 1/, 'document fallback must reject duplicate target selectors');
assert.match(picker, /control\.trigger\.classList\.remove\('is-invalid'\)/, 'applying a date must clear stale invalid styling');
assert.match(picker, /control\.trigger\.removeAttribute\('aria-invalid'\)/, 'applying a date must clear stale invalid accessibility state');
assert.equal((picker.match(/popup\.addEventListener\('click', handlePopupClick\)/g) || []).length, 1, 'The shared picker must retain one delegated popup click listener');
assert.match(tasks, /cleanupTaskCreateTransientState\(\{ closePanel: true \}\)/, 'successful task creation must close body-level pickers before refreshing the view');
assert.match(tasks, /cleanupTaskCreateTransientState\(\{ reset: true \}\)/, 'successful task creation must reset transient form state');
assert.match(tasks, /focusSafeTaskControl\(view\)/, 'successful task creation must focus a safe view control');
assert.match(tasks, /window\.taskCreateLifecycle\?\.cleanup\?\.\(\{ closePanel: true \}\)/, 'Cancel, X, Escape and view switching must use the shared cleanup lifecycle');
assert.match(portalCss, /task-form-grid__row--assignment \{[^}]*minmax\(180px,\.8fr\)[^}]*minmax\(240px,1\.2fr\)/);
assert.match(portalCss, /@media \(max-width:700px\)[\s\S]*task-form-grid__row--assignment \{ grid-template-columns:minmax\(0,1fr\)/);

console.log('Task combined due date-time checks passed.');
